// Golden reference for the AKAIZER stretch mode.
// The stretch routine below is copied unchanged from the Akaizer v1.2 Mac port
// (a port of Ben Burchett's 2006 Akaizer). Run:  node akaizer_ref.js > ../AkaizerGolden.h
"use strict";
const AK = (() => {
  const PI_VB = 3.141592654;
  function rint(x) {
    const f = Math.floor(x), d = x - f;
    if (d > 0.5) return f + 1;
    if (d < 0.5) return f;
    return (f % 2 === 0) ? f : f + 1;
  }
  function linkedFreq(cycleLen) { return rint(41000 / cycleLen); }
  function stretch(input, channels, sampleRate, stretchPct, cycleLen, cycleFreq) {
    const nIn = input.length;
    const factor = stretchPct / 100;
    const nOut = rint(nIn * factor);
    const L = cycleLen * 2 * channels;
    const C = rint((channels * sampleRate) / cycleFreq);
    const out = new Int16Array(Math.max(nOut, 0));
    if (nOut <= 0 || C <= 0) return { out, L, C, S: 0 };
    const S = rint(nIn / (nOut / C));
    const kMax = rint(nOut / C - 1);
    const ubIn = nIn - 1, ubOut = nOut - 1;
    for (let k = 0; k <= kMax; k++) {
      const ib = S * k, ob = C * k;
      for (let j = 0; j <= L - 1; j++) {
        if (ib + j > ubIn) break;
        if (ob + j > ubOut) break;
        const g = Math.sin(((j + 1) * PI_VB) / L);
        let v = rint(input[ib + j] * g + out[ob + j]);
        if (v > 32767) v = 32767; else if (v < -32768) v = -32768;
        out[ob + j] = v;
      }
    }
    return { out, L, C, S };
  }
  return { rint, linkedFreq, stretch };
})();

// the same integer-only test signal is made by EngineTest.cpp (akaizerTestInput)
function makeInput(words, seed, loud) {
  const v = new Int16Array(words);
  let s = seed >>> 0;
  for (let i = 0; i < words; i++) {
    s = (Math.imul(s, 1664525) + 1013904223) >>> 0;
    let x = ((i * 37) % 2000 - 1000) * 20 + ((s >>> 16) & 0x3fff) - 8192;
    if (loud && (i % 3000) < 1500) x = Math.trunc(x * 3 / 2);
    v[i] = Math.max(-32768, Math.min(32767, x));
  }
  return v;
}
function fnv(arr) {
  let h = 0x811c9dc5;
  for (let i = 0; i < arr.length; i++) {
    const u = arr[i] & 0xffff;
    h = Math.imul(h ^ (u & 0xff), 16777619) >>> 0;
    h = Math.imul(h ^ (u >>> 8), 16777619) >>> 0;
  }
  return h >>> 0;
}
// channels, frames, rate, stretch %, cycle, freq (0 = linked), loud
const cases = [
  [1, 4000, 44100, 100, 800, 0, 0],
  [1, 4000, 44100, 50, 300, 0, 0],
  [1, 4000, 44100, 213, 1000, 0, 0],
  [1, 3000, 22050, 400, 150, 120, 0],
  [2, 3000, 44100, 213, 333, 0, 0],
  [2, 3000, 48000, 50, 800, 77, 0],
  [2, 2000, 44100, 400, 20, 0, 0],
  [1, 6000, 44100, 100, 400, 0, 1],
  [1, 5000, 44100, 137.5, 777, 0, 1],
];
const lines = [];
cases.forEach((c, i) => {
  const [ch, frames, rate, pct, cycle, freq, loud] = c;
  const input = makeInput(frames * ch, 1000 + i, loud);
  const f = freq > 0 ? freq : AK.linkedFreq(cycle);
  const r = AK.stretch(input, ch, rate, pct, cycle, f);
  lines.push(`    { ${ch}, ${frames}, ${rate}, ${pct}, ${cycle}, ${freq}, ${loud}, ${1000 + i}u, ${r.out.length}, 0x${fnv(r.out).toString(16)}u, ${r.out[Math.floor(r.out.length / 2)]} },`);
});
